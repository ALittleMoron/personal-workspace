export const lighthouseI18nBundles = { ru, en };

export function assertLighthouseI18nFixture() {
  const expectedKeys = new Set(requiredMessageKeys);
  for (const [language, messages] of Object.entries(lighthouseI18nBundles)) {
    const messageKeys = Object.keys(messages);
    for (const key of requiredMessageKeys) {
      if (typeof messages[key] !== 'string' || messages[key].trim() === '') {
        throw new Error(`Lighthouse ${language} i18n fixture is missing ${key}`);
      }
    }
    for (const key of messageKeys) {
      if (!expectedKeys.has(key)) {
        throw new Error(`Lighthouse ${language} i18n fixture has an unexpected ${key}`);
      }
    }
    if (messageKeys.length !== requiredMessageKeys.length) {
      throw new Error(`Lighthouse ${language} i18n fixture does not match the required key set`);
    }
  }
}
